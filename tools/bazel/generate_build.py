#!/usr/bin/env python3
"""Write BUILD.bazel for every workspace crate and the CLI from their Cargo manifests and
`cargo metadata` (which gives each crate's resolved feature set). The vendored patches
(vendor/*) are not members: crate_universe generates their BUILD files in place when it resolves
the lockfile, and they reach the crates through `all_crate_deps` like any dependency. Rerun after
a dependency change: `python3 tools/bazel/generate_build.py`."""

import json
import pathlib
import subprocess
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = "# Generated by tools/bazel/generate_build.py from Cargo.toml; do not edit by hand.\n"


def snake(name: str) -> str:
    return name.replace("-", "_")


def main() -> None:
    dirs = sorted(ROOT.glob("crates/*")) + [ROOT / "apps/solidcraft-cli"]
    dirs = [d for d in dirs if (d / "Cargo.toml").exists()]
    crates = {}
    for d in dirs:
        m = tomllib.load(open(d / "Cargo.toml", "rb"))
        crates[m["package"]["name"]] = (d, m)
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1"], cwd=ROOT))
    features = {}
    for node in meta["resolve"]["nodes"]:
        pkg = next(p for p in meta["packages"] if p["id"] == node["id"])
        if pkg["name"] in crates and pkg["source"] is None:
            features[pkg["name"]] = sorted(node["features"])
    for name, (d, m) in crates.items():
        edition = m["package"].get("edition")
        if not isinstance(edition, str):
            edition = "2024"  # workspace inheritance
        deps, proc = [], []
        for dep, spec in m.get("dependencies", {}).items():
            pkg = spec.get("package", dep) if isinstance(spec, dict) else dep
            if pkg in crates:
                dd, dm = crates[pkg]
                label = f"//{dd.relative_to(ROOT).as_posix()}:{pkg}"
                (proc if dm.get("lib", {}).get("proc-macro") else deps).append(label)
        lib = m.get("lib", {})
        is_bin = "bin" in m and "lib" not in m and not (d / "src/lib.rs").exists()
        feats = features.get(name, [])
        lines = [HEADER]
        if is_bin:
            lines.append('load("@rules_rust//rust:defs.bzl", "rust_binary")')
        elif lib.get("proc-macro"):
            lines.append('load("@rules_rust//rust:defs.bzl", "rust_proc_macro")')
        else:
            lines.append('load("@rules_rust//rust:defs.bzl", "rust_library")')
        lines.append('load("@crates//:defs.bzl", "all_crate_deps")')
        has_build = (d / "build.rs").exists()
        if has_build:
            lines.append('load("@rules_rust//cargo:defs.bzl", "cargo_build_script")')
        lines.append("")
        lines.append('package(default_visibility = ["//visibility:public"])')
        lines.append("")
        lines.append('exports_files(["Cargo.toml"])')
        lines.append("")
        if has_build:
            # the build script sees the sources through CARGO_MANIFEST_DIR (crates/doc reads
            # src/format, crates/ui-egui its catalogs) and its OUT_DIR is handed to the crate
            lines.append("cargo_build_script(")
            lines.append('    name = "build_script",')
            lines.append('    srcs = ["build.rs"],')
            lines.append(f'    edition = "{edition}",')
            lines.append('    data = glob(["src/**", "assets/**", "i18n/**"], allow_empty = True),')
            lines.append("    deps = all_crate_deps(build = True),")
            lines.append("    proc_macro_deps = all_crate_deps(build_proc_macro = True),")
            lines.append(")")
            lines.append("")
            deps.append(":build_script")
        rule = "rust_binary" if is_bin else ("rust_proc_macro" if lib.get("proc-macro") else "rust_library")
        lines.append(f"{rule}(")
        lines.append(f'    name = "{name}",')
        lines.append(f'    crate_name = "{snake(name)}",')
        root = lib.get("path", "src/lib.rs")
        if is_bin:
            root = next(b["path"] for b in m["bin"] if b["name"] == name)
        lines.append(f'    crate_root = "{root}",')
        lines.append('    srcs = glob(["src/**/*.rs"]),')
        # non-Rust files beside the sources (shaders, catalogs, scenarios) and the repository
        # files the crates embed (licences, assets); unused inputs cost nothing but a hash
        extra = ', "//tools/bazel:zig-cc-aarch64.sh"' if is_bin else ""
        lines.append(f'    compile_data = glob(["src/**", "tests/**"], exclude = ["**/*.rs"], allow_empty = True) + ["//:embedded"{extra}],')
        lines.append(f'    edition = "{edition}",')
        if feats:
            lines.append("    crate_features = [" + ", ".join(f'"{f}"' for f in feats) + "],")
        lines.append("    deps = all_crate_deps(normal = True)" + (" + [" + ", ".join(f'"{x}"' for x in sorted(deps)) + "]" if deps else "") + ",")
        lines.append("    proc_macro_deps = all_crate_deps(proc_macro = True)" + (" + [" + ", ".join(f'"{x}"' for x in sorted(proc)) + "]" if proc else "") + ",")
        if is_bin:
            # aarch64 links through a wrapper of zig's cc (see tools/bazel/zig-cc-aarch64.sh)
            lines.append("    rustc_flags = select({")
            lines.append('        "@platforms//cpu:aarch64": ["-Clinker=tools/bazel/zig-cc-aarch64.sh"],')
            lines.append('        "//conditions:default": [],')
            lines.append("    }),")

        lines.append(")")
        (d / "BUILD.bazel").write_text("\n".join(lines) + "\n")
    print(f"wrote BUILD.bazel for {len(crates)} crates")


if __name__ == "__main__":
    main()
